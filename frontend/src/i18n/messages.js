function resolve(dict, key) {
  return key.split(".").reduce((acc, part) => acc?.[part], dict);
}

export function createTranslator(locale) {
  const dict = messages[locale] || messages.ru;

  return function t(key, params = {}) {
    let value = resolve(dict, key);
    if (value == null) return key;
    if (typeof value !== "string") return String(value);

    return value.replace(/\{(\w+)\}/g, (_, name) => {
      if (params[name] == null) return `{${name}}`;
      return String(params[name]);
    });
  };
}

export function getMessageList(locale, key) {
  const value = resolve(messages[locale] || messages.ru, key);
  return Array.isArray(value) ? value : [];
}
